-- Sections: a user subscribes to a slot (the same sport lesson every two weeks, SportQueueRules.slotKey) and
-- Backend queues every occurrence through an ordinary auto entry as soon as its forecast prototype, the slot's
-- lesson two weeks earlier, is published. Subscribers of a slot are a queue of their own in (created_at, id) order.
CREATE TABLE sport_section_subscriptions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL,
    slot_key varchar(255) NOT NULL,
    source_lesson_id bigint NOT NULL,
    -- The end of the latest occurrence whose prototype was published; the slot has left the timetable once it is
    -- two periods old.
    last_opened_ends_at timestamp(6) with time zone NOT NULL,
    status varchar(16) NOT NULL DEFAULT 'ACTIVE',
    stop_reason varchar(16),
    stopped_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT fk_sport_section_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_sport_section_source FOREIGN KEY (source_lesson_id) REFERENCES sport_lessons (id),
    CONSTRAINT ck_sport_section_status CHECK (status IN ('ACTIVE', 'STOPPED')),
    CONSTRAINT ck_sport_section_stop_reason CHECK (stop_reason IN ('USER', 'EXPIRED')),
    CONSTRAINT ck_sport_section_stopped CHECK (
        (status = 'STOPPED') = (stop_reason IS NOT NULL) AND (stop_reason IS NULL) = (stopped_at IS NULL)
    )
);
-- One active subscription per slot and user; the slot's queue is read in subscription order.
CREATE UNIQUE INDEX uq_sport_section_active ON sport_section_subscriptions (user_id, slot_key) WHERE status = 'ACTIVE';
CREATE INDEX idx_sport_section_slot_queue ON sport_section_subscriptions (slot_key, created_at, id) WHERE status = 'ACTIVE';

-- One row per handled occurrence, so an occurrence is queued at most once: QUEUED with its entry, LIMIT when the
-- monthly limit had no free slot, SKIPPED when the user turned this one date off.
CREATE TABLE sport_section_occurrences (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id bigint NOT NULL,
    starts_at timestamp(6) with time zone NOT NULL,
    ends_at timestamp(6) with time zone NOT NULL,
    state varchar(16) NOT NULL,
    entry_id bigint,
    CONSTRAINT fk_sport_section_occurrence_subscription FOREIGN KEY (subscription_id)
        REFERENCES sport_section_subscriptions (id) ON DELETE CASCADE,
    CONSTRAINT fk_sport_section_occurrence_entry FOREIGN KEY (entry_id) REFERENCES sport_auto_sign_entries (id) ON DELETE SET NULL,
    CONSTRAINT uq_sport_section_occurrence UNIQUE (subscription_id, starts_at),
    CONSTRAINT ck_sport_section_occurrence_state CHECK (state IN ('QUEUED', 'LIMIT', 'SKIPPED')),
    CONSTRAINT ck_sport_section_occurrence_order CHECK (ends_at > starts_at)
);
CREATE INDEX idx_sport_section_occurrence_entry ON sport_section_occurrences (entry_id) WHERE entry_id IS NOT NULL;

